def katakana_to_hiragana(value: str) -> str:
    return "".join(chr(ord(char) - 0x60) if 0x30A1 <= ord(char) <= 0x30F6 else char for char in value)


def normalize_japanese(value: str) -> str:
    value = re.sub(r"\s+", " ", value.strip())
    return katakana_to_hiragana(value).replace("ッ", "っ")



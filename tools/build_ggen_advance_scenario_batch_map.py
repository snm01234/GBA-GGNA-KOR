JAPANESE_RE = re.compile(r"[ぁ-んァ-ヶ一-龥々〆ヵ]")


def punctuation_only(value: str) -> bool:
    return not re.search(r"[ぁ-んァ-ヶ一-龥々〆ヵA-Za-z0-9]", value)


def translate_segment(source_text: str) -> str | None:
    key = normalize_japanese(source_text)
    if not key:
        return ""
    exact = PHRASES.get(key)
    if exact is not None:
        return exact
    # Pure pauses and emphasis carry no lexical content.  Keep their visual
    # rhythm, while replacing Japanese small-tsu emphasis with punctuation.
    if punctuation_only(key):
        return key.replace("っ", "!").replace("ー", "—")
    # A few highly regular variants can be safely normalized to a known line.
    compact = key.replace(" ", "")
    for suffix, target in (
        ("やらせるか", "그렇게 둘까"),
        ("やらせるものか", "그렇게 둘까"),
        ("やられるものか", "당할 줄 알았나"),
        ("やられるもんか", "당할 줄 알았나"),
        ("やるしかない", "할 수밖에 없어"),
        ("なめるな", "얕보지 마라"),
        ("かすっただけだ", "스쳤을 뿐이다"),
        ("どうってことない", "아무것도 아니야"),
        ("どうってことはない", "아무것도 아니다"),
        ("パワーダウン", "출력 저하"),
    ):
        normalized_suffix = normalize_japanese(suffix)
        if compact == normalized_suffix or compact.startswith(normalized_suffix):
            tail = compact[len(normalized_suffix) :]
            # Only accept punctuation/elongation tails; particles and words
            # require an explicit natural sentence entry.
            if punctuation_only(tail):
                return target + tail.replace("っ", "!")
    # Do not emit a partially translated Japanese sentence.
    return None


def decode_slots(slots: list[str], charmap: dict[int, str]) -> str | None:
    values: list[str] = []
    for raw_slot in slots:
        try:
            slot = int(str(raw_slot), 16)
        except (TypeError, ValueError):
            return None
        value = charmap.get(slot)
        if value is None:
            return None
        values.append(value)
    return "".join(values)


def parse_offset(row: dict[str, Any]) -> int:
    try:
        return int(str(row.get("target_file_offset", "0")), 16)
    except (TypeError, ValueError):
        return 0


def load_charmap(path: Path) -> dict[int, str]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    result = {int(key, 16): value for key, value in payload["verified_charmap"].items()}
    result.update(CORRECTED_LOW_KANA)
    return result


def row_is_decodable(row: dict[str, Any], charmap: dict[int, str]) -> bool:
    """Allow a supplemental charmap to unlock a source row without mutating it."""
    for raw_slot in row.get("source_unresolved_slots", []):
        try:
            if int(str(raw_slot), 16) not in charmap:
                return False
        except (TypeError, ValueError):
            return False
    return True


def build_map(
    merged: dict[str, Any],
    scenario: dict[str, Any],
    charmap: dict[int, str],
    max_records: int,
    start_offset: int,
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    scenario_by_id = {row["record_id"]: row for row in scenario["main"]["records"]}
    pending = [
        row
        for row in merged["records"]
        if row.get("translation_status") == "pending"
        and row.get("translation_policy") == "translate"
        and row.get("semantic_category") == "scenario_event_text"
        and row_is_decodable(row, charmap)
        and parse_offset(row) >= start_offset
    ]
    pending.sort(key=lambda row: (parse_offset(row), row["record_id"]))
    selected: list[dict[str, Any]] = []
    stats: Counter[str] = Counter()
    for row in pending:
        source_row = scenario_by_id.get(row["record_id"])
        if source_row is None:
            stats["missing_scenario_source"] += 1
            continue
        translations: list[str] = []
        failed = False
        for segment in source_row.get("segments", []):
            slots = segment.get("slots", [])
            if not slots:
                translations.append("")
                continue
            decoded = decode_slots(slots, charmap)
            translated = None if decoded is None else translate_segment(decoded)
            if translated is None or JAPANESE_RE.search(translated):
                failed = True
                stats["uncovered_segment"] += 1
                break
            translations.append(translated)
        if failed:
            continue
        # The compact map is checked against the immutable source by the
        # overlay binder; keeping the full segment list preserves controls and
        # blank pointer slots exactly.
        selected.append(
            {
                "record_id": row["record_id"],
                "translation_segments": translations,
                "translation_ko": "\n".join(value for value in translations if value),
                "translation_status": "translated",
                "translator_notes": "12x12 battle dialogue batch; control segments preserved; corrected low-kana decoder applied",
            }
        )
        stats["selected"] += 1
        if len(selected) >= max_records:
            break
    stats["pending_candidates"] = len(pending)
    stats["available_before_limit"] = stats["selected"]
    return selected, dict(stats)


